void Canvas::rect(int x, int y, int w, int h, Rgba c)
{
	const int x0 = std::max(x, 0), y0 = std::max(y, 0);
	const int x1 = std::min(x + w, int(m_w)), y1 = std::min(y + h, int(m_h));
	for (int yy = y0; yy < y1; yy++)
	{
		uint8_t* row = m_px + size_t(yy) * m_stride;
		for (int xx = x0; xx < x1; xx++)
		{
			uint8_t* p = row + size_t(xx) * 4;
			p[0] = c.r;
			p[1] = c.g;
			p[2] = c.b;
			p[3] = c.a;
		}
	}
}

void Canvas::image(int x, int y, int w, int h, const uint8_t* rgba)
{
	for (int yy = std::max(y, 0); yy < std::min(y + h, int(m_h)); yy++)
		for (int xx = std::max(x, 0); xx < std::min(x + w, int(m_w)); xx++)
		{
			const uint8_t* s = rgba + (size_t(yy - y) * w + (xx - x)) * 4;
			uint8_t* p = m_px + size_t(yy) * m_stride + size_t(xx) * 4;
			const int a = s[3];
			for (int k = 0; k < 3; k++)
				p[k] = uint8_t((s[k] * a + p[k] * (255 - a) + 127) / 255);
			p[3] = 255;
		}
}

int Canvas::text(int x, int y, int scale, std::string_view s, Rgba c)
{
	int cx = x;
	for (char ch : s)
	{
		const Glyph* g = find_glyph(ch);
		for (int row = 0; row < 7; row++)
			for (int col = 0; col < 5; col++)
				if (g->rows[row] & (0x10 >> col))
					rect(cx + col * scale, y + row * scale, scale, scale, c);
		cx += 6 * scale;
	}
	return cx - x;
}

