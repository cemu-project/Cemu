const Glyph* find_glyph(char c)
{
	if (c >= 'a' && c <= 'z')
		c = char(c - 'a' + 'A');
	for (const auto& g : kFont)
		if (g.ch == c)
			return &g;
	return &kFont[0]; // unknown -> space
}

